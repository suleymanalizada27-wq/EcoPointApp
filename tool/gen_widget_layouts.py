#!/usr/bin/env python3
"""Emits the five home-screen widget layouts + the panel drawables.

Only FrameLayout / LinearLayout / TextView / ImageView are used (the RemoteViews
whitelist). Every layout shares the same view ids, so EpWidgetProvider.kt sets
them all; RemoteViews silently skips ids a layout does not contain.

  ep_widget_xl  4x4 premium      ep_widget_l  4x2 compact
  ep_widget_s   2x2 mini         ep_widget_xs 2x1      ep_widget  3x2

Usage: python3 tool/gen_widget_layouts.py
"""
import pathlib

OUT = pathlib.Path(__file__).resolve().parent / "android_res" / "widget"
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n'
NOTE = "<!-- Generated by tool/gen_widget_layouts.py. RemoteViews-safe views only. -->\n"


def a(**kw):
    return " ".join(f'android:{k}="{v}"' for k, v in kw.items())


def tv(id, size, color="@color/ef_w_ink", bold=True, lines=1, w="wrap_content", h="wrap_content", **kw):
    base = dict(id=f"@+id/{id}", layout_width=w, layout_height=h, includeFontPadding="false",
                maxLines=lines, ellipsize="end", text="", textColor=color, textSize=f"{size}sp")
    if bold:
        base["textStyle"] = "bold"
    base.update(kw)
    return f"<TextView {a(**base)} />\n"


def lin(inner, orient="horizontal", w="match_parent", h="wrap_content", **kw):
    d = dict(layout_width=w, layout_height=h, orientation=orient)
    d.update(kw)
    return f"<LinearLayout {a(**d)}>\n{inner}</LinearLayout>\n"


def img(id, w, h, src, scale="fitCenter", **kw):
    d = dict(id=f"@+id/{id}", layout_width=w, layout_height=h, src=src, scaleType=scale)
    d.update(kw)
    return f"<ImageView {a(**d)} />\n"


def chip(fl, ts, pad_h):
    """Streak chip: flame + number."""
    inner = img("ep_widget_flame", f"{fl}dp", f"{fl}dp", "@drawable/ep_widget_flame",
                importantForAccessibility="no")
    inner += tv("ep_widget_streak", ts, "@color/ef_w_flame", layout_marginStart="4dp")
    return lin(inner, id="@+id/ep_widget_streak_chip", w="wrap_content", gravity="center_vertical",
               background="@drawable/ep_widget_chip", paddingStart="8dp", paddingEnd="10dp",
               paddingTop=f"{pad_h}dp", paddingBottom=f"{pad_h}dp")


def bar(seg_h, off="@drawable/ep_widget_seg_off", **kw):
    segs = ""
    for i in range(10):
        on = (f'<LinearLayout {a(id=f"@+id/ep_widget_seg_{i}", layout_width="match_parent", layout_height="match_parent", background="@drawable/ep_widget_seg_on", visibility="gone")} />')
        segs += (f'<FrameLayout {a(layout_width="0dp", layout_height=f"{seg_h}dp", layout_weight="1", layout_marginEnd="3dp" if i < 9 else "0dp", background=off)}>{on}</FrameLayout>\n')
    return lin(segs, id="@+id/ep_widget_bar_row", gravity="center_vertical", **kw)


def dots(size):
    out = ""
    for i in range(7):
        out += tv(f"ep_widget_day_{i}", 8, "#FFFFFFFF", w=f"{size}dp", h=f"{size}dp",
                  layout_marginStart="3dp", background="@drawable/ep_widget_day_off", gravity="center")
    return lin(out, w="wrap_content", gravity="center_vertical")


def balance_row(bs, us, mb="3dp"):
    return lin(tv("ep_widget_balance", bs, text="—", maxLines=1) +
               tv("ep_widget_unit", us, "@color/ef_w_green_lip", layout_marginStart="4dp", layout_marginBottom=mb, text="EP"),
               w="wrap_content", gravity="bottom")


def bubble(size, lines, pad_v):
    return tv("ep_widget_msg", size, lines=lines, w="match_parent", background="@drawable/ep_widget_bubble",
              paddingStart="12dp", paddingEnd="12dp", paddingTop=f"{pad_v}dp", paddingBottom=f"{pad_v}dp")


def panel(id, inner, orient="vertical", w="match_parent", h="wrap_content", pad="10dp", pv="8dp", **kw):
    return lin(inner, orient=orient, w=w, h=h, id=f"@+id/{id}", background="@drawable/ep_w_panel_light",
               paddingStart=pad, paddingEnd=pad, paddingTop=pv, paddingBottom=pv, **kw)


def btn(id, text, size, weight, h, ghost=False, ml="6dp"):
    return tv(id, size, "@color/ef_w_ink", w="0dp", h=f"{h}dp", layout_weight=weight, layout_marginStart=ml,
              gravity="center", text=text, paddingStart="6dp", paddingEnd="6dp",
              background="@drawable/ep_widget_btn_ghost" if ghost else "@drawable/ep_widget_btn")


def root(body, art):
    bg = img("ep_widget_bgimg", "match_parent", "match_parent", f"@drawable/ep_w_bg_day_{art}",
             scale="fitXY", importantForAccessibility="no")
    return (HEAD + NOTE + f'<FrameLayout {NS} {a(id="@+id/ep_widget_root", layout_width="match_parent", layout_height="match_parent")}>\n'
            + bg + body + "</FrameLayout>\n")


def mascot(w, h="match_parent", **kw):
    return img("ep_widget_mascot", w, h, "@drawable/ecofriend_w_day", contentDescription="EcoFriend", **kw)


# ---------------------------------------------------------------- 4x4
def xl():
    top = lin(lin(bubble(13, 3, 8), w="0dp", layout_weight="1", layout_marginEnd="8dp") + chip(18, 18, 4),
              gravity="center_vertical")
    p1 = panel("ep_w_p1",
               tv("ep_widget_label", 10, text="EcoPoint", color="@color/ef_w_ink") +
               balance_row(30, 13) +
               lin(tv("ep_widget_level", 12, w="0dp", layout_weight="1") + tv("ep_widget_week", 10, bold=False), gravity="center_vertical", layout_marginTop="2dp") +
               tv("ep_widget_impact", 10, bold=False, layout_marginTop="2dp"),
               w="0dp", layout_weight="1", layout_gravity="center_vertical")
    mid = lin(mascot("0dp", layout_weight="1") + lin(p1, orient="vertical", w="0dp", layout_weight="1", gravity="center_vertical", h="match_parent", layout_marginStart="2dp"),
              h="0dp", layout_weight="1", layout_marginTop="4dp", gravity="center_vertical")
    goal = panel("ep_w_p2",
                 lin(tv("ep_widget_goal_label", 11, w="0dp", layout_weight="1", text="") + dots(11) +
                     tv("ep_widget_goal", 11, layout_marginStart="8dp"), gravity="center_vertical") +
                 bar(8, off="@drawable/ep_w_seg_off_p", layout_marginTop="6dp"),
                 layout_marginTop="6dp")
    cta = lin(btn("ep_widget_btn_scan", "Scan", 15, "1.5", 42, ml="0dp") +
              btn("ep_widget_btn_missions", "Missions", 11, "1", 42, ghost=True) +
              btn("ep_widget_btn_history", "History", 11, "1", 42, ghost=True),
              layout_marginTop="8dp", gravity="center_vertical")
    body = lin(top + mid + goal + cta, orient="vertical", h="match_parent", padding="12dp")
    return root(body, "sq")


# ---------------------------------------------------------------- 4x2
def streak_inline(fl, ts):
    """Flame + number without a chip background (sits inside a panel)."""
    inner = img("ep_widget_flame", f"{fl}dp", f"{fl}dp", "@drawable/ep_widget_flame", importantForAccessibility="no")
    inner += tv("ep_widget_streak", ts, "@color/ef_w_flame", layout_marginStart="3dp")
    return lin(inner, id="@+id/ep_widget_streak_chip", w="wrap_content", gravity="center_vertical", layout_marginTop="1dp")


def l():
    p1 = panel("ep_w_p1", balance_row(20, 10, "2dp") + streak_inline(12, 11),
               w="0dp", layout_weight="1", pad="10dp", pv="3dp")
    row = lin(p1 + btn("ep_widget_btn_scan", "Scan", 13, "0", 44, ml="6dp").replace('layout_width="0dp"', 'layout_width="72dp"'),
              layout_marginTop="4dp", gravity="center_vertical")
    goal = lin(lin(bar(5), w="0dp", layout_weight="1") +
               tv("ep_widget_goal", 11, "#FFFFFFFF", layout_marginStart="8dp", shadowColor="#66000000", shadowDy="1", shadowRadius="2"),
               layout_marginTop="5dp", gravity="center_vertical")
    right = lin(bubble(11, 2, 5) + row + goal, orient="vertical", w="0dp", layout_weight="1", h="match_parent",
                gravity="center_vertical", layout_marginStart="2dp")
    body = lin(mascot("92dp") + right, h="match_parent", gravity="center_vertical", padding="8dp")
    return root(body, "wide")


# ---------------------------------------------------------------- 2x2
def s():
    col = lin(lin(mascot("match_parent"), h="0dp", layout_weight="1", gravity="center") +
              panel("ep_w_p1",
                    lin(balance_row(24, 11, "2dp"), gravity="center_horizontal") +
                    bar(5, off="@drawable/ep_w_seg_off_p", layout_marginTop="5dp"),
                    pad="10dp", pv="6dp"),
              orient="vertical", h="match_parent")
    chip_view = chip(14, 13, 3).replace("<LinearLayout ", "<LinearLayout " + a(layout_gravity="top|end") + " ", 1)
    body = (f'<FrameLayout {a(layout_width="match_parent", layout_height="match_parent", padding="10dp")}>\n'
            + col + chip_view + "</FrameLayout>\n")
    return root(body, "sq")


# ---------------------------------------------------------------- 2x1
def xs():
    p1 = panel("ep_w_p1", balance_row(22, 11, "2dp") + tv("ep_widget_label", 9, text="EcoPoint", bold=False),
               w="0dp", layout_weight="1", pad="10dp", pv="4dp", layout_marginStart="6dp")
    body = lin(mascot("52dp") + p1 + lin(chip(14, 13, 3), w="wrap_content", layout_marginStart="6dp"),
               h="match_parent", gravity="center_vertical", padding="8dp")
    return root(body, "wide")


# ---------------------------------------------------------------- 3x2
def m():
    p1 = panel("ep_w_p1", balance_row(24, 12, "2dp") + tv("ep_widget_label", 9, text="EcoPoint", bold=False),
               w="0dp", layout_weight="1", pad="10dp", pv="5dp")
    row = lin(p1 + lin(chip(14, 14, 4), w="wrap_content", layout_marginStart="6dp"), layout_marginTop="6dp",
              gravity="center_vertical")
    right = lin(bubble(11, 2, 6) + row, orient="vertical", w="0dp", layout_weight="1", h="match_parent",
                gravity="center_vertical", layout_marginStart="4dp")
    body = lin(mascot("92dp") + right, h="match_parent", gravity="center_vertical", padding="10dp")
    return root(body, "wide")


DRAWABLES = {
    "ep_w_panel_light": '''<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item><shape android:shape="rectangle"><solid android:color="#26000000" /><corners android:radius="16dp" /></shape></item>
    <item android:bottom="2dp"><shape android:shape="rectangle"><solid android:color="#F2FFFFFF" /><stroke android:width="1dp" android:color="#80FFFFFF" /><corners android:radius="16dp" /></shape></item>
</layer-list>''',
    "ep_w_panel_dark": '''<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item><shape android:shape="rectangle"><solid android:color="#33000000" /><corners android:radius="16dp" /></shape></item>
    <item android:bottom="2dp"><shape android:shape="rectangle"><solid android:color="#40FFFFFF" /><stroke android:width="1dp" android:color="#59FFFFFF" /><corners android:radius="16dp" /></shape></item>
</layer-list>''',
    "ep_w_seg_off_p": '''<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle"><solid android:color="#40708070" /><corners android:radius="4dp" /></shape>''',
}

if __name__ == "__main__":
    for name, fn in [("ep_widget_xl", xl), ("ep_widget_l", l), ("ep_widget_s", s), ("ep_widget_xs", xs), ("ep_widget", m)]:
        (OUT / f"{name}.xml").write_text(fn())
    for name, body in DRAWABLES.items():
        (OUT / f"{name}.xml").write_text(HEAD + body + "\n")
    print("ok")
